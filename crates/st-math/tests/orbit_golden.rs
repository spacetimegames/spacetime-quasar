//! Golden tests for `st_math::orbit` (ADR 0008).
//!
//! Every function is checked on at least 16 inputs against expected results committed as
//! IEEE-754 bit patterns, so a change in `libm`, in the algorithm or in a platform's
//! arithmetic shows up as a failing test on every target. The tables are bit patterns
//! recorded from `st_math::orbit` (libm 0.2.16) on the reference dev machine; they are the
//! cross-platform contract, not an independent check of the physics. The physics is checked
//! in `orbit.rs`.

#![allow(
    clippy::type_complexity,
    clippy::approx_constant,
    reason = "golden tables are tuples of literal inputs, including pi-like values"
)]

use st_math::glam::DVec3;
use st_math::orbit::{Elements, StateVectors, solve_kepler};

/// Asserts that two values have the same bit pattern, printing both in hex on failure.
#[track_caller]
fn assert_bits(name: &str, input: &dyn core::fmt::Debug, got: f64, want: u64) {
    assert_eq!(
        got.to_bits(),
        want,
        "{name}({input:?}): got {:#018x} ({got:?}), want {want:#018x} ({:?})",
        got.to_bits(),
        f64::from_bits(want),
    );
}

#[track_caller]
fn assert_all_bits(name: &str, input: &dyn core::fmt::Debug, got: &[f64], want: &[u64]) {
    assert_eq!(got.len(), want.len());
    for (k, (g, w)) in got.iter().zip(want).enumerate() {
        assert_bits(&format!("{name}[{k}]"), input, *g, *w);
    }
}

fn elements(a: [f64; 6]) -> Elements {
    Elements {
        semi_major_axis: a[0],
        eccentricity: a[1],
        inclination: a[2],
        longitude_of_ascending_node: a[3],
        argument_of_periapsis: a[4],
        mean_anomaly: a[5],
    }
}

fn elements_array(e: &Elements) -> [f64; 6] {
    [
        e.semi_major_axis,
        e.eccentricity,
        e.inclination,
        e.longitude_of_ascending_node,
        e.argument_of_periapsis,
        e.mean_anomaly,
    ]
}

fn state(p: [f64; 3], v: [f64; 3]) -> StateVectors {
    StateVectors {
        position: DVec3::from_array(p),
        velocity: DVec3::from_array(v),
    }
}

fn state_array(s: &StateVectors) -> [f64; 6] {
    let (p, v) = (s.position, s.velocity);
    [p.x, p.y, p.z, v.x, v.y, v.z]
}

