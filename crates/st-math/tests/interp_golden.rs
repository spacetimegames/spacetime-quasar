//! Golden tests for `st_math::interp` (ADR 0008).
//!
//! Every function is checked on at least 16 inputs against expected results committed as
//! IEEE-754 bit patterns, so a change in `libm`, in the algorithm or in a platform's
//! arithmetic shows up as a failing test on every target. The tables are bit patterns
//! recorded from `st_math::interp` (libm 0.2.16) on the reference dev machine; they are the
//! cross-platform contract, not an independent check of the maths. The maths is checked in
//! `interp.rs`. Quaternion inputs are given as an axis and an angle and are built here with
//! `st_math::det`, so the inputs themselves do not depend on a platform libm.

#![allow(
    clippy::type_complexity,
    clippy::approx_constant,
    reason = "golden tables are tuples of literal inputs, including pi-like values"
)]

